@pytest.mark.asyncio
async def test_request_id_generation_and_propagation():
    """Verify X-Request-ID correlation header is generated or preserved across requests."""
    async with AsyncClient(app=app, base_url="http://test") as client:
        # 1. Autogenerated request ID
        res = await client.get("/health")
        assert res.status_code == 200
        req_id = res.headers.get("X-Request-ID")
        assert req_id is not None
        assert req_id.startswith("req_")
        assert "X-Response-Time" in res.headers

        # 2. Preserved client-supplied request ID
        custom_id = "trace-client-corr-9988"
        res_custom = await client.get("/health", headers={"X-Request-ID": custom_id})
        assert res_custom.status_code == 200
        assert res_custom.headers.get("X-Request-ID") == custom_id


@pytest.mark.asyncio
async def test_standardized_error_envelope_and_no_stack_trace_leak():
    """Verify 404 and 422 error envelopes contain request_id and sanitize stack traces."""
    async with AsyncClient(app=app, base_url="http://test") as client:
        custom_id = "err-trace-7744"
        # Test 404
        res = await client.get("/api/v1/non-existent-route-xyz", headers={"X-Request-ID": custom_id})
        assert res.status_code == 404
        assert res.headers.get("X-Request-ID") == custom_id
        
        data = res.json()
        assert "error" in data
        err = data["error"]
        assert err["code"] == "NOT_FOUND"
        assert err["request_id"] == custom_id
        assert "timestamp" in err
        # Ensure no raw python traceback is present in message or details
        assert "Traceback" not in str(data)
        assert "File \"" not in str(data)

        # Test 422 Validation Error
        val_res = await client.post(
            "/api/v1/auth/login",
            json={"email": "not-an-email"},  # missing password
            headers={"X-Request-ID": "val-trace-5566"},
        )
        assert val_res.status_code == 422
        val_data = val_res.json()
        assert "error" in val_data
        assert val_data["error"]["code"] == "VALIDATION_ERROR"
        assert val_data["error"]["request_id"] == "val-trace-5566"
        assert "errors" in val_data["error"]["details"]


