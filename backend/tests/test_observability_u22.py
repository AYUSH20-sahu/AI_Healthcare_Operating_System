@pytest.mark.asyncio
async def test_ai_provider_telemetry_instrumentation():
    """Verify calling LLM, STT, and TTS records metrics into TelemetryCollector."""
    # 1. LLM call
    llm = get_llm_provider()
    res = await llm.generate([LLMMessage(role="user", content="Patient has exertional chest pain")])
    assert res.content is not None
    assert res.latency_ms >= 0

    # 2. STT call
    stt = get_stt_provider()
    stt_res = await stt.transcribe(b"dummy-audio-content", format="webm")
    assert stt_res.text is not None

    # 3. TTS call
    tts = get_tts_provider()
    tts_res = await tts.synthesize("Take two tablets daily.")
    assert len(tts_res.audio_data) > 0

    # 4. Check telemetry was recorded
    metrics = telemetry_collector.get_metrics()
    ai_metrics = metrics["ai_call_metrics"]
    assert ai_metrics["total_ai_calls"] >= 1
    assert "token_usage" in ai_metrics
    assert ai_metrics["token_usage"]["total_tokens"] >= 0


def test_structured_json_log_formatter():
    """Verify JSONLogFormatter outputs valid JSON with expected structured fields."""
    formatter = JSONLogFormatter()
    record = logging.LogRecord(
        name="aihos.test",
        level=logging.INFO,
        pathname="test.py",
        lineno=10,
        msg="Consultation session started",
        args=(),
        exc_info=None,
    )
    setattr(record, "path", "/api/v1/telehealth/session")
    setattr(record, "method", "POST")
    setattr(record, "status_code", 200)
    setattr(record, "latency_ms", 45.2)

    current_request_id.set("req_unit_test_999")
    formatted = formatter.format(record)

    data = json.loads(formatted)
    assert data["level"] == "INFO"
    assert data["logger"] == "aihos.test"
    assert data["message"] == "Consultation session started"
    assert data["request_id"] == "req_unit_test_999"
    assert data["path"] == "/api/v1/telehealth/session"
    assert data["method"] == "POST"
    assert data["status_code"] == 200
    assert data["latency_ms"] == 45.2
    assert "timestamp" in data
